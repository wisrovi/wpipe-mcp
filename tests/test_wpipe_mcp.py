def test_search_wpipe_step_returns_results():
    results = [
        {"origin": "Official", "func_name": "vision_yolo", "description": "YOLO vision step", "namespace": "wpipe_plugins.vision"},
        {"origin": "Community", "func_name": "csv_reader", "description": "CSV reader step", "namespace": "wpipe_plugins"},
    ]
    catalog_mock = mock.MagicMock()
    catalog_mock.search.return_value = results
    with mock.patch.object(server, "get_catalog", return_value=catalog_mock):
        text = server.search_wpipe_step("yolo")
    assert "vision_yolo" in text
    assert "Official" in text
    assert "Community" in text


def test_search_wpipe_step_no_results():
    catalog_mock = mock.MagicMock()
    catalog_mock.search.return_value = []
    with mock.patch.object(server, "get_catalog", return_value=catalog_mock):
        text = server.search_wpipe_step("zzz_nope")
    assert "No custom step matching 'zzz_nope' was found" in text


