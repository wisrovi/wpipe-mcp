def test_validate_wpipe_project_line_limit_and_nested_function_violations(tmp_path):
    """
    Validates that validate_wpipe_project strictly detects and flags:
    1. Source files exceeding 200 lines (Modularity & Single Responsibility).
    2. Nested function definitions (closures inside functions or methods).
    """
    target = str(tmp_path / "modularity_violating_project")
    server.deploy_wpipe_scaffolding(
        target,
        project_name="ModularityApp",
        pipeline_type="microservice",
        include_tests=True,
    )

    # 1. Inject a state file with > 200 lines
    long_state_file = (
        tmp_path / "modularity_violating_project" / "app" / "states" / "step_long.py"
    )
    long_content = (
        "from wpipe import step\n@step()\nclass LongStep:\n    def __call__(self, ctx):\n        return ctx\n"
        + ("# line\n" * 210)
    )
    long_state_file.write_text(long_content)

    # 2. Inject a state file with a nested function definition
    nested_state_file = (
        tmp_path / "modularity_violating_project" / "app" / "states" / "step_nested.py"
    )
    nested_content = (
        "from wpipe import step\n"
        "@step()\n"
        "class NestedStep:\n"
        "    def __call__(self, ctx):\n"
        "        def inner_helper(val):\n"
        "            return val * 2\n"
        "        return inner_helper(ctx)\n"
    )
    nested_state_file.write_text(nested_content)

    report = server.validate_wpipe_project(target)
    assert "Compliance Issues & Warnings" in report
    assert "Modularity violation: File" in report
    assert "exceeds 200 lines" in report
    assert "step_long.py" in report
    assert (
        "Architectural violation: Nested function definition 'inner_helper'" in report
    )
    assert "step_nested.py" in report


def test_validate_wpipe_project_duplicate_pipeline_names(tmp_path):
    """
    Validates that validate_wpipe_project detects duplicate pipeline variable names
    calling .set_steps() in pipelines.py to guarantee multi-DAG extension rendering.
    """
    target = str(tmp_path / "dup_pipeline_project")
    server.deploy_wpipe_scaffolding(
        target,
        project_name="DupPipeApp",
        pipeline_type="microservice",
        include_tests=True,
    )

    pipelines_file = tmp_path / "dup_pipeline_project" / "app" / "pipelines.py"

    # Inject duplicate variable names
    dup_content = (
        "from wpipe import Pipeline\n"
        "from states.step_a import InferenceStep\n\n"
        "def create_a():\n"
        "    pipeline = Pipeline('pipe_a')\n"
        "    pipeline.set_steps([InferenceStep()])\n"
        "    return pipeline\n\n"
        "def create_b():\n"
        "    pipeline = Pipeline('pipe_b')\n"
        "    pipeline.set_steps([InferenceStep()])\n"
        "    return pipeline\n"
    )
    pipelines_file.write_text(dup_content)

    report = server.validate_wpipe_project(target)
    assert "Compliance Issues & Warnings" in report
    assert "Duplicate pipeline variable name(s)" in report
    assert "pipeline" in report

    # Fix with distinct variable names and Google docstrings
    distinct_content = (
        '"""Pipeline declarations."""\n\n'
        "from wpipe import Pipeline\n"
        "from states.step_a import InferenceStep\n\n"
        "def create_a() -> Pipeline:\n"
        '    """Build pipeline A.\n\n'
        "    Returns:\n"
        "        Pipeline: Constructed instance.\n"
        '    """\n'
        "    pipe_a = Pipeline('pipe_a')\n"
        "    pipe_a.set_steps([InferenceStep()])\n"
        "    return pipe_a\n\n"
        "def create_b() -> Pipeline:\n"
        '    """Build pipeline B.\n\n'
        "    Returns:\n"
        "        Pipeline: Constructed instance.\n"
        '    """\n'
        "    pipe_b = Pipeline('pipe_b')\n"
        "    pipe_b.set_steps([InferenceStep()])\n"
        "    return pipe_b\n"
    )
    pipelines_file.write_text(distinct_content)

    report_fixed = server.validate_wpipe_project(target)
    assert "Compliance Status: Fully Compliant" in report_fixed
    assert (
        "Verified distinct pipeline variable naming in 'pipelines.py'" in report_fixed
    )


